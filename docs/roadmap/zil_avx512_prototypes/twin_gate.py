#!/usr/bin/env python3
"""gate2.py — drive the table-driven twin gate over the zil tree.

For every avx2 codelet with a PROVENANCE recipe: derive (geometry class, table class)
from the recipe flags, emit the avx2 twin AND the avx512 twin with the SAME generator
binary (so generator drift vs the shipped files is not mistaken for an avx512 bug),
compile both (-O3 -march=native -ffp-contract=off), and write arms2.h for twin2.c.
Recipes whose class the gate does not model yet are listed as SKIP with the reason;
GEN_FAIL / CC_FAIL are listed too. Usage: gate2.py <gen_radix.exe> <zil/avx2 dir> <workdir>
"""
import os, re, subprocess, sys, concurrent.futures as cf

G, Z, W = sys.argv[1], sys.argv[2], sys.argv[3]
POL = os.environ.get("VFFT_TAIL512", "ladder")
os.makedirs(os.path.join(W, "src"), exist_ok=True)
os.makedirs(os.path.join(W, "obj"), exist_ok=True)
CFLAGS = ["-O3", "-march=native", "-fpermissive", "-w", "-ffp-contract=off"]

def classify(flags):
    f = set(flags)
    if "--k1-mono" in f or any(x.startswith("--zp-") for x in f):
        return None, "not a cil kind (k1-mono / zp split family): separate gate"
    if "--cil-turnst" in f or "--cil-turnst-gs" in f or "--cil-n1t" in f:
        return None, "corner-turn store (N1T) not emitted at avx512 yet"
    kind = next((x for x in flags if x.startswith("--cil-") and x[6:] in
                 ("n1", "n1c", "n1ccs", "t2", "t2c", "t2cp", "t2cs", "t2csg", "t2csgt", "t2csgn", "t2csgnt")), None)
    if kind is None:
        return None, "unmodelled kind"
    k = kind[6:]
    row = "--cil-rowloop" in f
    if k == "n1":   return (("G_ROW" if row else "G_LEG"), "T_NONE"), None
    if k == "n1c":  return ("G_LEGIP", "T_NONE"), None
    if k == "n1ccs": return ("G_CS", "T_NONE"), None
    if k == "t2":   return (("G_ROW" if row else "G_LEG"), "T_STREAM"), None
    if k in ("t2c", "t2cp"): return ("G_DIGIT", "T_DIGIT"), None
    if k == "t2cs": return ("G_CS", "T_STREAM"), None
    if k in ("t2csg", "t2csgt"): return ("G_CS", "T_GEN2"), None
    if k in ("t2csgn", "t2csgnt"): return ("G_GN", "T_GEN2N"), None
    return None, "unmodelled kind"

def sym_of(path, isa):
    txt = open(path).read()
    syms = re.findall(r"^void (\w+_%s)\(" % isa, txt, re.M)
    return syms[-1] if syms else None   # the exported (wrapper) symbol is last

def one(rel):
    path = os.path.join(Z, rel)
    txt = open(path).read()
    m = re.search(r"^ \* Generated by: \S*gen_radix\.exe (.*)$", txt, re.M)
    if not m:
        return ("NOPROV", rel, "")
    args = m.group(1).split()
    envm = re.search(r"^ \* Env overrides: (.*)$", txt, re.M)
    env = dict(os.environ)
    if envm and not envm.group(1).startswith("(none)"):
        for t in envm.group(1).split():
            if "=" in t: kk, vv = t.split("=", 1); env[kk] = vv
    cls, why = classify(args)
    if cls is None:
        return ("SKIP", rel, why)
    R = int(args[0])
    base = rel.replace("/", "_")[:-2]
    out = {}
    for isa, uarch in (("avx2", "raptor_lake_avx2"), ("avx512", "sapphire_rapids_avx512")):
        a = [x for x in args]
        i = a.index("--isa"); a[i + 1] = isa
        if "--uarch" in a: j = a.index("--uarch"); a[j + 1] = uarch
        e = dict(env); e["VFFT_TAIL512"] = POL
        src = os.path.join(W, "src", "%s__%s.c" % (base, isa))
        r = subprocess.run([G] + a, env=e, capture_output=True, text=True)
        if r.returncode:
            return ("GEN_FAIL", rel, (r.stderr.strip().splitlines() or ["?"])[-1][:160])
        open(src, "w").write(r.stdout)
        obj = src.replace("/src/", "/obj/")[:-2] + ".o"
        sym = sym_of(src, isa)
        uniq = "g_%s__%s" % (re.sub(r"\W", "_", base), isa)
        c = subprocess.run(["gcc"] + CFLAGS + (["-D%s=%s" % (sym, uniq)] if sym else []) + ["-c", src, "-o", obj], capture_output=True, text=True)
        if c.returncode:
            err = next((l for l in c.stderr.splitlines() if "error" in l), "?")
            return ("CC_FAIL", rel, "%s: %s" % (isa, err[:160]))
        out[isa] = (uniq if sym else None, obj)
    if not out["avx2"][0] or not out["avx512"][0]:
        return ("SKIP", rel, "symbol not found")
    return ("ARM", rel, (cls, R, out))

rels = sorted(os.path.relpath(os.path.join(d, f), Z) for d, _, fs in os.walk(Z) for f in fs if f.endswith(".c"))
with cf.ThreadPoolExecutor(4) as ex:
    res = list(ex.map(one, rels))
arms, objs = [], []
with open(os.path.join(W, "status.tsv"), "w") as st:
    for v, rel, d in res:
        if v == "ARM":
            (geo, tab), R, out = d
            arms.append((rel, geo, tab, R, out["avx2"][0], out["avx512"][0]))
            objs += [out["avx2"][1], out["avx512"][1]]
            st.write("ARM\t%s\t%s %s\n" % (rel, geo, tab))
        else:
            st.write("%s\t%s\t%s\n" % (v, rel, d))
with open(os.path.join(W, "arms2.h"), "w") as h:
    for a in arms:
        for s in a[4:6]:
            h.write("void %s(const double*,const double*,double*,double*,const double*,const double*,size_t,size_t,size_t,size_t,size_t);\n" % s)
    h.write("static const arm_t arms[] = {\n")
    for rel, geo, tab, R, s2, s5 in arms:
        h.write('  { "%s", %s, %s, %d, %s, %s },\n' % (rel, geo, tab, R, s2, s5))
    h.write("};\n")
open(os.path.join(W, "objs.txt"), "w").write("\n".join(objs) + "\n")
from collections import Counter
print(Counter(v for v, _, _ in res))
