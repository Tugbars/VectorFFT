#!/bin/bash
# A/B one zil recipe at a given ISA: baseline gen vs new gen; print SAME/DIFF/FAIL
# usage: ab_one.sh <isa avx2|avx512> <rel>
W=/tmp/claude-0/-home-user-VectorFFT/207882f8-0ee5-5dd9-bdc8-3e5ddb7a3abd/scratchpad/wf1/turn
Z=/home/user/VectorFFT/src/dag-fft-compiler/codelets/zil/avx2
isa="$1"; rel="$2"; f="$Z/$rel"
line=$(grep -m1 '^ \* Generated by: ' "$f" | sed 's/^ \* Generated by: //')
[ -z "$line" ] && { printf 'NOPROV\t%s\n' "$rel"; exit 0; }
envl=$(grep -m1 '^ \* Env overrides: ' "$f" | sed 's/^ \* Env overrides: //')
args=${line#* }
if [ "$isa" = avx512 ]; then args=$(echo "$args" | sed -E 's/--isa avx2/--isa avx512/; s/--uarch [a-z0-9_]+/--uarch sapphire_rapids_avx512/'); fi
envs=(); case "$envl" in "(none)"*|"") ;; *) for t in $envl; do [[ "$t" == *=* ]] && envs+=("$t"); done;; esac
o="$W/ab_$isa/$(echo ${rel%.c} | tr / _)"
mkdir -p "$W/ab_$isa"
env "${envs[@]}" $W/bin_base/gen_radix.exe $args > "$o.base.c" 2> "$o.base.err"; rb=$?
env "${envs[@]}" $W/bin_new/gen_radix.exe  $args > "$o.new.c"  2> "$o.new.err";  rn=$?
if [ $rb -ne 0 ] && [ $rn -ne 0 ]; then printf 'BOTHFAIL\t%s\t%s\n' "$rel" "$(tail -1 $o.new.err | head -c 150)";
elif [ $rn -ne 0 ]; then printf 'NEWFAIL\t%s\t%s\n' "$rel" "$(tail -1 $o.new.err | head -c 150)";
elif [ $rb -ne 0 ]; then printf 'NEWONLY\t%s\n' "$rel";
elif cmp -s "$o.base.c" "$o.new.c"; then printf 'SAME\t%s\n' "$rel";
else printf 'DIFF\t%s\n' "$rel"; fi
