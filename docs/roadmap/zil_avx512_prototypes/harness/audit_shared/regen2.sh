#!/bin/bash
# regenerate avx2 original from its recipe and compare bytes
Z=/home/user/VectorFFT/src/dag-fft-compiler/codelets/zil/avx2
G=/tmp/claude-0/-home-user-VectorFFT/207882f8-0ee5-5dd9-bdc8-3e5ddb7a3abd/scratchpad/_build/default/bin/gen_radix.exe
W=/tmp/claude-0/-home-user-VectorFFT/207882f8-0ee5-5dd9-bdc8-3e5ddb7a3abd/scratchpad/wf1/audit_a/regen2
f="$1"; rel="${f#$Z/}"
line=$(grep -m1 '^ \* Generated by: ' "$f" | sed 's/^ \* Generated by: //')
envl=$(grep -m1 '^ \* Env overrides: ' "$f" | sed 's/^ \* Env overrides: //')
args=${line#* }
envs=(); case "$envl" in "(none)"*) ;; *) for t in $envl; do [[ "$t" == *=* ]] && envs+=("$t"); done;; esac
o="$W/$(echo $rel | tr / _)"
env "${envs[@]}" "$G" $args > "$o" 2>/dev/null
if cmp -s "$o" "$f"; then echo "SAME $rel"; else echo "DIFF $rel"; fi
