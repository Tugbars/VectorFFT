#!/bin/bash
# run_one.sh <rel path under zil/avx2, e.g. pair2p/radix4_z_t2_avx2.c> [twin path override]
# Builds + runs the differential driver for one (avx2 original, avx512 twin) pair.
S=/tmp/claude-0/-home-user-VectorFFT/207882f8-0ee5-5dd9-bdc8-3e5ddb7a3abd/scratchpad
W=$S/wf1/audit_b
Z=/home/user/VectorFFT/src/dag-fft-compiler/codelets/zil/avx2
rel="$1"
orig=$Z/$rel
twin=${2:-${TWIN_DIR:-$S/a512/out}/$(echo ${rel%_avx2.c} | tr / _)_avx512.c}
tag=$(basename "$twin" .c)
B=$W/${BLD:-bld}/$tag; mkdir -p $B
recipe=$(grep -m1 '^ \* Generated by: gen_radix' "$twin" | sed 's/^ \* Generated by: gen_radix.exe //')
radix=$(echo $recipe | awk '{print $1}')
dir=-1; [[ "$recipe" == *--cil-bwd* ]] && dir=1
row=0; [[ "$recipe" == *--cil-rowloop* ]] && row=1
if [[ "$recipe" == *--cil-n1ccs* ]]; then kind=3
elif [[ "$recipe" == *--cil-t2* ]]; then
  if [[ "$recipe" == *--cil-pretw* || $dir == -1 ]]; then kind=0; else kind=1; fi
elif [[ "$recipe" == *--cil-n1* ]]; then kind=2
else echo -e "SKIP\t$rel\tunknown recipe: $recipe"; exit 0; fi
symA=$(grep -oE '^void [A-Za-z0-9_]+\(' "$orig" | head -1 | sed 's/^void //; s/($//')
symB=$(grep -oE '^void [A-Za-z0-9_]+\(' "$twin" | head -1 | sed 's/^void //; s/($//')
CF="-O2 -march=native -ffp-contract=off"
gcc $CF -c "$orig" -o $B/a.o 2>$B/a.err || { echo -e "CC_A_FAIL\t$rel"; exit 0; }
gcc $CF -c "$twin" -o $B/b.o 2>$B/b.err || { echo -e "CC_B_FAIL\t$rel"; exit 0; }
gcc $CF -DSYM_A=$symA -DSYM_B=$symB -DRADIX=$radix -DKIND=$kind -DDIRS=$dir -DROWLOOP=$row \
    $W/drv.c $B/a.o $B/b.o -o $B/t -lm 2>$B/d.err || { echo -e "LINK_FAIL\t$rel\t$(head -c 200 $B/d.err)"; exit 0; }
out=$(timeout 300 $B/t) || out="CRASH_OR_TIMEOUT"
echo -e "$rel\tR=$radix kind=$kind dir=$dir row=$row\t$out"
