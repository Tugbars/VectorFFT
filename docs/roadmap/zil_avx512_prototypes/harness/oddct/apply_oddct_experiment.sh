#!/bin/bash
# apply_oddct_experiment.sh [avx512|avx2]  (default avx512)
#
# EXPERIMENT, not a corpus change: rewrites IN PLACE the odd-composite (9, 15, 21, 25,
# 27) kernels of the flat DIT and 2D kinds (shared/, shared/col/, flat/, rows/, chain3/;
# pair2p/ already ships raced _ct twins, ztt/ and flat/odd_mid/ are other families)
# with the factored construction (--cil-oddct: 9 -> 3x3, 15 -> 3x5, 21 -> 3x7,
# 25 -> 5x5, 27 -> 3x9), under their PLAIN symbol names. The factored form becomes
# the only form for those kernels, so a build of the tree measures it end to end.
#
# Every kernel is regenerated from its own provenance line plus --cil-oddct, so the
# recipe is otherwise unchanged. Revert with:
#   git checkout -- src/dag-fft-compiler/codelets/zil/<isa>
# (the corpus gate will report these files as drifted until reverted).
#
# Measured in the cloud session (docs/roadmap/zil_avx512_problems.md §1): at radix 25,
# AVX-512, factored t2cp 1.07-1.48x and n1c 1.40-1.94x faster at the kernel level; with
# every file of this script applied the flat DIT sweep (72,207 checks), the 2D IL test
# and the API smoke test stay correct.
#
# Needs the generator built with the scoped targets (never a bare dune build):
#   cd src/dag-fft-compiler/generator && dune build bin/gen_radix.exe
set -e
ISA=${1:-avx512}
REPO=$(git rev-parse --show-toplevel)
G=$REPO/src/dag-fft-compiler/generator/_build/default/bin/gen_radix.exe
Z=$REPO/src/dag-fft-compiler/codelets/zil/$ISA
[ -x "$G" ] || { echo "build gen_radix.exe first (see header)"; exit 2; }
[ -d "$Z" ] || { echo "no $Z"; exit 2; }
cd "$Z"
n=0
for f in $(ls shared/radix{9,15,21,25,27}_z_*.c shared/col/radix{9,15,21,25,27}_z_*.c \
              flat/radix{9,15,21,25,27}_z_*.c rows/radix{9,15,21,25,27}_z_*.c \
              chain3/radix{9,15,21,25,27}_z_*.c 2>/dev/null | grep -v "_ct_"); do
    line=$(grep -m1 '^ \* Generated by: ' "$f" | sed 's/^ \* Generated by: //')
    [ -z "$line" ] && continue
    case "$line" in *--cil-oddct*) continue;; esac   # already applied
    args="${line#* }"
    d=$(mktemp -d)
    (cd "$d" && "$G" $args --cil-oddct > o.c)
    sed -i -E "s/_ct_(fwd|bwd)_$ISA/_\1_$ISA/g" "$d/o.c"
    mv "$d/o.c" "$f"; rm -rf "$d"
    n=$((n + 1))
done
echo "rewrote $n $ISA kernels in the factored form; rebuild the library to measure"
