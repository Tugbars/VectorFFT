#!/usr/bin/env python3
"""toolchain.py - the ONE place the baseline tools learn about the host.

WHY THIS EXISTS
---------------
The tools were written on the owner's Windows/MinGW box and hardcoded
C:\\mingw152 paths in four places, plus a `.exe` suffix in a fifth. On any other
host the ladder either aborted or, worse, one rung ran against a tool that was
not there. Every script now asks this module instead:

  - CC / NM / OBJDUMP / READELF / AR: from the environment, then PATH, then (on
    Windows) the historical mingw152 install;
  - the executable suffix (".exe" on Windows only, as gauntlet/build.py does);
  - the object format (ELF or COFF);
  - the FLAGS KEY: compiler version, host CPU model, OS and ISA. A reference is
    valid only within one key; the key names the reference directory, so a
    comparison across hosts or compilers cannot happen by accident;
  - the include set, GENERATED by the same recursive walk both build systems
    use (a frozen list silently misses a new directory);
  - the shipped driver flags (gauntlet/build.py's own build_cmd), loaded per ISA.

It never decides anything about the library.
"""
import hashlib
import importlib.util
import os
import platform
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
CORE = os.path.join(ROOT, "src", "core")
DAG = os.path.join(ROOT, "src", "dag-fft-compiler")
DAG_GEN = os.path.join(DAG, "generator", "generated")
IS_WINDOWS = os.name == "nt"
EXE = ".exe" if IS_WINDOWS else ""
ISAS = ("avx2", "avx512")

_MINGW = r"C:\mingw152\mingw64\bin"


def tool(name):
    """Resolve a binutils/gcc tool: env override, then PATH, then mingw152."""
    env = os.environ.get(name.upper())
    if env:
        return env
    found = shutil.which(name)
    if found:
        return found
    if IS_WINDOWS:
        cand = os.path.join(_MINGW, name + ".exe")
        if os.path.exists(cand):
            return cand
    raise SystemExit("toolchain: cannot find %r (set %s or put it on PATH)"
                     % (name, name.upper()))


def cc():
    return os.environ.get("CC") or tool("gcc")


def nm():
    return tool("nm")


def objdump():
    return tool("objdump")


def readelf():
    return tool("readelf")


def cc_version():
    out = subprocess.run([cc(), "-dumpfullversion"], capture_output=True,
                         text=True).stdout.strip()
    return out or "unknown"


def cpu_model():
    try:
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def obj_format(path):
    with open(path, "rb") as f:
        magic = f.read(4)
    return "ELF" if magic == b"\x7fELF" else "COFF"


def flags_key(isa):
    """The directory name of a reference: os-compiler-version-isa-cpuhash.

    The CPU model is part of the key because the shipped build is
    -march=native: an -O3 object from another CPU model is a different object.
    It is hashed (the model string has spaces and '@')."""
    osname = "win" if IS_WINDOWS else platform.system().lower()
    cpu = hashlib.sha1(cpu_model().encode()).hexdigest()[:6]
    return "%s-gcc%s-%s-cpu%s" % (osname, cc_version(), isa, cpu)


def include_dirs():
    """The -I set, walked exactly like gauntlet/build.py build_includes() and
    CMake's GLOB_RECURSE: include/, the compiler dir, generated/, jit/, then
    src/core and every subdirectory, sorted."""
    core_dirs = [CORE] + sorted(
        os.path.join(dp, d) for dp, dns, _ in os.walk(CORE) for d in dns)
    return ([os.path.join(ROOT, "include"), DAG, DAG_GEN, os.path.join(DAG, "jit")]
            + core_dirs)


def include_flags():
    return ["-I" + d for d in include_dirs()]


def identity_flags(isa):
    """The PORTABLE identity object's flags: no -march=native, no -w.

    avx2 is -O2 -mavx2 -mfma, exactly the historical identity key. avx512 adds
    the two flags build_isa.h tests (-mavx512f -mavx512dq), as CMake does."""
    f = ["-O2", "-mavx2", "-mfma"]
    if isa == "avx512":
        f += ["-mavx512f", "-mavx512dq"]
    return f


def load_build_py(isa):
    """gauntlet/build.py as a module, with its ISA fixed at import (it reads
    VFFT_ISA into a module constant). A fresh module per call, so an avx2 and
    an avx512 load never share state."""
    saved = os.environ.get("VFFT_ISA")
    os.environ["VFFT_ISA"] = isa
    try:
        spec = importlib.util.spec_from_file_location(
            "vfft_build_py_" + isa, os.path.join(ROOT, "gauntlet", "build.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod
    finally:
        if saved is None:
            os.environ.pop("VFFT_ISA", None)
        else:
            os.environ["VFFT_ISA"] = saved


def shipped_flags(isa):
    """The shipped driver flags for vfft.c: gauntlet/build.py's build_cmd, no
    MKL/FFTW, no fingerprint, no warn key. Returned without -I (the caller adds
    the generated include set) so the two include sets cannot drift apart."""
    env_saved = {k: os.environ.pop(k, None)
                 for k in ("VFFT_FINGERPRINT", "VFFT_WARN", "VFFT_ASAN")}
    try:
        bp = load_build_py(isa)
        tc = bp.detect_toolchain()
        cflags, _, _ = bp.build_cmd(tc, os.path.join(CORE, "vfft.c"),
                                    os.path.join(HERE, "_unused" + EXE),
                                    extra_srcs=[], split=True)
    finally:
        for k, v in env_saved.items():
            if v is not None:
                os.environ[k] = v
    return [f for f in cflags if not f.startswith("-I")]


def run(cmd, **kw):
    kw.setdefault("cwd", ROOT)
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_sha():
    r = run(["git", "rev-parse", "HEAD"])
    sha = r.stdout.strip()
    dirty = run(["git", "status", "--porcelain", "--untracked-files=no"]).stdout.strip()
    return sha + (" (dirty)" if dirty else "")


if __name__ == "__main__":
    for isa in ISAS:
        print("%-7s key=%s" % (isa, flags_key(isa)))
    print("cc=%s nm=%s objdump=%s" % (cc(), nm(), objdump()))
    print("include dirs: %d" % len(include_dirs()))
    print("shipped avx512:", " ".join(shipped_flags("avx512")))
