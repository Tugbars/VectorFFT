(* emit_ztt_registry.ml — auto-generate the ZTURN-T driver registry.
 *
 * Derived from the SAME cell list the driver TU is emitted from
 * (Ztt_drivers.cells), so a driver that exists is reachable and a cell the
 * runtime asks for either has all four drivers or is refused at create.
 *
 * Usage:
 *   dune exec bin/emit_ztt_registry.exe > generated/ztt_registry_avx2.h
 *)

let () =
  let isa = "avx2" in
  let cells = Ztt_drivers.cells () in
  let p = print_string in
  p "/* auto-generated by emit_ztt_registry.exe (Ztt_drivers.cells) — do not edit */\n";
  p "#ifndef VFFT_ZTT_REGISTRY_AVX2_H\n#define VFFT_ZTT_REGISTRY_AVX2_H\n#include <stddef.h>\n\n";
  p "/* the fused driver ABI: zin (natural packed z), zout (natural packed z), plane\n";
  p " * (2N doubles, 64-B; unused by the dest drivers), tw (ONE contiguous stream in\n";
  p " * stage order), rb (the run-base table, N/R0 entries) */\n";
  Printf.printf "typedef void (*vfft_ztt_fn)(%s);\n\n" Ztt_drivers.driver_params;
  List.iter
    (fun (n, ch) ->
       List.iter
         (fun (bwd, dest) ->
            Printf.printf "extern void %s(%s);\n" (Ztt_drivers.driver_name ~isa n ch ~bwd ~dest) Ztt_drivers.driver_params)
         [ false, true; false, false; true, true; true, false ])
    cells;
  p "\ntypedef struct {\n    int n, nf;\n    int chain[7];\n";
  p "    vfft_ztt_fn fwd_dest, fwd_plane, bwd_dest, bwd_plane;\n} vfft_ztt_cell_t;\n\n";
  Printf.printf "#define VFFT_ZTT_NCELLS_AVX2 %d\n" (List.length cells);
  p "static const vfft_ztt_cell_t vfft_ztt_cells_avx2[VFFT_ZTT_NCELLS_AVX2] = {\n";
  List.iter
    (fun (n, ch) ->
       let nf = List.length ch in
       let chain = String.concat ", " (List.map string_of_int (ch @ List.init (7 - nf) (fun _ -> 0))) in
       Printf.printf
         "    { %d, %d, { %s }, %s, %s, %s, %s },\n"
         n
         nf
         chain
         (Ztt_drivers.driver_name ~isa n ch ~bwd:false ~dest:true)
         (Ztt_drivers.driver_name ~isa n ch ~bwd:false ~dest:false)
         (Ztt_drivers.driver_name ~isa n ch ~bwd:true ~dest:true)
         (Ztt_drivers.driver_name ~isa n ch ~bwd:true ~dest:false))
    cells;
  p "};\n\n#endif /* VFFT_ZTT_REGISTRY_AVX2_H */\n"
;;
