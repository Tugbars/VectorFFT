(* emit_zts_registry.ml — auto-generate the zturn-ts driver registry.
 *
 * Derived from the SAME cell list the driver files are emitted from
 * (Zts_drivers.cells), so a driver that exists is reachable and a cell the
 * runtime asks for either has all its drivers or is refused at create.
 *
 * Usage:
 *   dune exec bin/emit_zts_registry.exe -- --isa avx2 > generated/zts_registry_avx2.h
 *)

let () =
  let isa =
    match List.tl (Array.to_list Sys.argv) with
    | [ "--isa"; v ] -> v
    | [] -> "avx2"
    | _ -> failwith "emit_zts_registry: usage: [--isa avx2|avx512]"
  in
  let vw = (Isa.of_name isa).Isa.vec_width in
  let cells = Zts_drivers.cells ~vw () in
  let up = String.uppercase_ascii isa in
  let p = print_string in
  p "/* auto-generated by emit_zts_registry.exe (Zts_drivers.cells) — do not edit.\n";
  p " * zturn-ts: the SPLIT library's ZTURN-T. The functions listed here are its FUSED\n";
  p " * CODELETS (generator/generated/fused_codelets/zts_*, ztv_*): whole-transform\n";
  p " * functions with the stage kernels of codelets/split/ztt inlined, bound whole by\n";
  p " * split/rank1/zts.h. The stage kernels are the product. */\n";
  Printf.printf "#ifndef VFFT_ZTS_REGISTRY_%s_H\n#define VFFT_ZTS_REGISTRY_%s_H\n#include <stddef.h>\n\n" up up;
  p "/* S (K=1, split planes): in_re/in_im (natural), out_re/out_im (natural; == in in\n";
  p " * place), plane (the block interior, 2N doubles + slack, placed per call), tw (ONE\n";
  p " * contiguous stream in stage order, ZTURN-T's quad records), rb (the run-base\n";
  p " * table, N/R0 entries), tile (0 = untiled). The _batch twin loops K contiguous\n";
  p " * transforms at offset t*N. */\n";
  Printf.printf "typedef void (*vfft_zts_fn)(%s);\n" (Zts_drivers.driver_params Zts_drivers.S);
  Printf.printf "typedef void (*vfft_zts_bfn)(%s, size_t K);\n\n" (Zts_drivers.driver_params Zts_drivers.S);
  p "/* V (lane-major K, data[e*K + t], K a multiple of VW): the two lane-major planes in\n";
  p " * and out, two scratch planes (N*VW doubles each + slack: ONE lane group at a time),\n";
  p " * tw = (c, s) pairs per (column, leg) in stage order, rb, tile, K. */\n";
  Printf.printf "typedef void (*vfft_ztv_fn)(%s);\n\n" (Zts_drivers.driver_params Zts_drivers.V);
  List.iter
    (fun (n, ch) ->
       List.iter
         (fun bwd ->
            Printf.printf
              "extern void %s(%s);\n"
              (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.S n ch ~bwd)
              (Zts_drivers.driver_params Zts_drivers.S);
            Printf.printf
              "extern void %s_batch(%s, size_t K);\n"
              (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.S n ch ~bwd)
              (Zts_drivers.driver_params Zts_drivers.S);
            Printf.printf
              "extern void %s(%s);\n"
              (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.V n ch ~bwd)
              (Zts_drivers.driver_params Zts_drivers.V))
         [ false; true ])
    cells;
  p "\ntypedef struct {\n    int n, nf;\n    int chain[7];\n";
  p "    vfft_zts_fn s_fwd, s_bwd;          /* K=1, split planes (the plane form) */\n";
  p "    vfft_zts_bfn s_fwd_batch, s_bwd_batch;   /* K contiguous transforms */\n";
  p "    vfft_ztv_fn v_fwd, v_bwd;          /* lane-major K, a multiple of VW */\n";
  p "} vfft_zts_cell_t;\n\n";
  Printf.printf "#define VFFT_ZTS_NCELLS_%s %d\n" up (List.length cells);
  Printf.printf "static const vfft_zts_cell_t vfft_zts_cells_%s[VFFT_ZTS_NCELLS_%s] = {\n" isa up;
  List.iter
    (fun (n, ch) ->
       let r = Array.of_list ch in
       let nf = Array.length r in
       Printf.printf
         "    { %d, %d, { %s }, %s, %s, %s_batch, %s_batch, %s, %s },\n"
         n
         nf
         (String.concat ", " (List.init 7 (fun i -> if i < nf then string_of_int r.(i) else "0")))
         (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.S n ch ~bwd:false)
         (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.S n ch ~bwd:true)
         (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.S n ch ~bwd:false)
         (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.S n ch ~bwd:true)
         (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.V n ch ~bwd:false)
         (Zts_drivers.driver_name ~isa ~fam:Zts_drivers.V n ch ~bwd:true))
    cells;
  p "};\n\n#endif\n"
;;
